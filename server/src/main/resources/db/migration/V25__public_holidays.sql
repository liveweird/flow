-- Every date an admin had typed into the old free-form list survives under the generic name 'Holiday'. The seed ran
-- first, so where both name a date the seed's name wins (ON CONFLICT DO NOTHING). Only well-formed ISO dates are carried
-- (the settings PUT validated them, this guards the column width).
INSERT INTO metrics.public_holidays (holiday_date, name, created_at)
SELECT DISTINCT h.value, 'Holiday', 1792022400000
FROM metrics.settings s, jsonb_array_elements_text(s.holidays) AS h(value)
WHERE h.value ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
ON CONFLICT (holiday_date) DO NOTHING;

ALTER TABLE metrics.settings DROP COLUMN holidays;

-- The seeded holidays change working days, so every derived number is stale: this does what
-- `MetricsSettingsService.bumpRevision()` does for a settings PUT. The shared revision moves (dim_date is rewritten by the
-- first DERIVE running at the current revision) and one scheduler-priority DERIVE (priority 10, max_attempts 3 = the
-- `ingest.maxAttempts` default) is enqueued for every enabled, active connection, stamped with the connection's own
-- config_revision; ON CONFLICT DO NOTHING coalesces into an already open DERIVE (`uq_sync_jobs_open_per_kind`).
UPDATE metrics.settings SET config_revision = config_revision + 1 WHERE id = 1;

INSERT INTO public.sync_jobs (connection_id, kind, status, priority, config_revision, requested_at, attempt, max_attempts)
SELECT c.id, 'DERIVE', 'PENDING', 10, c.config_revision, (EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::BIGINT, 0, 3
FROM public.source_connections c
WHERE c.enabled AND NOT c.marked_as_deleted
ON CONFLICT DO NOTHING;
