-- The public-holiday dictionary (Lettuce's V39/V41, ported): ADMIN-curated dates on which nobody works. It REPLACES the
-- free-form `metrics.settings.holidays` array and feeds the one working calendar (`metrics/WorkingCalendar.kt`) — so a
-- holiday is non-working everywhere (dim_date, DEFAULT capacity, every report) and is locked OFF in capacity calendars.
-- Hard delete (the Lettuce registry exception, documented in `.claude/docs/persistence.md`): nothing references a holiday
-- by FK, and a removed row is simply re-added. UNIQUE (holiday_date) backstops racing creates (23505 -> the central 409).
CREATE TABLE metrics.public_holidays (
    id            SERIAL       PRIMARY KEY,
    holiday_date  VARCHAR(10)  NOT NULL,  -- ISO YYYY-MM-DD (lexicographic == chronological)
    name          VARCHAR(100) NOT NULL,
    created_at    BIGINT       NOT NULL,  -- epoch millis
    UNIQUE (holiday_date)
);

