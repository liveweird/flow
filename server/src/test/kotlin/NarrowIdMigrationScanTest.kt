package ch.nokillswit

import java.nio.file.Path
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.name
import kotlin.io.path.readText
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Static scan over the SQL files in `db/migration` (checkup 3, D9-3): no migration newer than [LAST_GRANDFATHERED_VERSION] may create a
 * 32-bit (or narrower) surrogate id in the `raw`, `norm` or `metrics` schemas - an `integer`/`int`/`int4`/`smallint` column that is
 * `SERIAL`, `IDENTITY` or has a `nextval` default, a single-column integer primary key (inline or `PRIMARY KEY (col)`) that is not a
 * foreign key, an `ALTER COLUMN ... TYPE` back to a narrow integer, or a sequence declared `AS integer|smallint`. Those schemas hold
 * the rows PROCESS / DERIVE / the raw streams delete and re-insert whole on every run, and a sequence is never reset by a DELETE, so
 * an int32 id runs dry in a few years (the dev stack spent 8.3 M ids in 26 days). Use `BIGSERIAL` / `BIGINT`, or a natural composite key.
 * A `SET search_path` is refused too: every table name is matched by its schema prefix, and a search path would hide it.
 *
 * It is a proportionate regex scan, not a SQL parser: schema-qualified names (quoted or not), `UNLOGGED`, `IF [NOT] EXISTS` and `ONLY`
 * are understood; dynamic SQL (`EXECUTE`, `DO` blocks) is not and needs a reviewer's eye.
 *
 * V33 widened the eleven tables that DERIVE/PROCESS rewrite, which is why the cut-off is V33: every migration up to it is immutable
 * and not scanned (it still declares narrow ids: V13/V16's `SERIAL`s that V33 widened, V15's singleton `metrics.settings`, its
 * `team_membership` and `derive_runs`, V24's `team_capacity_defaults` and V25's `public_holidays`, plus V6/V8/V9 in `public`). The
 * detector is itself pinned against samples and against V13/V15/V16 (a scan that cannot see the old `SERIAL`s proves nothing).
 */
class NarrowIdMigrationScanTest {
    private val migrationDir = Path.of("src/main/resources/db/migration")

    @Test
    fun `no migration after V33 creates a 32-bit id in raw, norm or metrics`() {
        val offenders = migrations().filter { (version, _) -> version > LAST_GRANDFATHERED_VERSION }
            .flatMap { (_, file) -> narrowIdFindings(file.readText()).map { "${file.name}: $it" } }
        assertEquals(
            emptyList(),
            offenders,
            "use BIGSERIAL / BIGINT (or a natural composite key) for ids in raw/norm/metrics - an int32 sequence runs dry (D9-3)",
        )
    }

    @Test
    fun `the detector sees the int32 ids V13 and V16 declared and nothing in V33 that widened them`() {
        val byVersion = migrations().toMap()
        assertEquals(3, narrowIdFindings(byVersion.getValue(13).readText()).size, "V13: three norm.* tables with id SERIAL")
        assertEquals(8, narrowIdFindings(byVersion.getValue(16).readText()).size, "V16: eight metrics.* tables with id SERIAL")
        assertEquals(1, narrowIdFindings(byVersion.getValue(15).readText()).count { "metrics.settings" in it })
        assertEquals(emptyList(), narrowIdFindings(byVersion.getValue(24).readText()), "V24's FK-keyed team_capacity_defaults is not an id")
        assertEquals(emptyList(), narrowIdFindings(byVersion.getValue(33).readText()))
    }

    @Test
    fun `the detector flags narrow ids and spares wide ones, natural keys, foreign keys and other schemas`() {
        fun hits(sql: String) = narrowIdFindings(sql).size
        // Flagged: serials, identity, nextval defaults, narrow single-column keys, narrowing ALTERs, narrow sequences, search_path.
        assertEquals(1, hits("CREATE TABLE metrics.x (id SERIAL PRIMARY KEY, a INT);"))
        assertEquals(1, hits("create table norm.x (id serial primary key);"))
        assertEquals(1, hits("CREATE TABLE raw.x (id SMALLSERIAL PRIMARY KEY);"))
        assertEquals(1, hits("CREATE TABLE metrics.x (id INTEGER PRIMARY KEY, a TEXT);"))
        assertEquals(1, hits("CREATE TABLE metrics.x (a TEXT, n int4 NOT NULL PRIMARY KEY);"))
        assertEquals(1, hits("ALTER TABLE raw.x ADD COLUMN id SERIAL;"))
        assertEquals(1, hits("CREATE TABLE metrics.x (id INTEGER GENERATED ALWAYS AS IDENTITY, a TEXT, PRIMARY KEY (id));"))
        assertEquals(1, hits("CREATE TABLE metrics.x (id INT GENERATED BY DEFAULT AS IDENTITY UNIQUE, a TEXT);"))
        assertEquals(1, hits("CREATE TABLE metrics.x (id integer NOT NULL DEFAULT nextval('metrics.s'), a TEXT, PRIMARY KEY (id));"))
        assertEquals(1, hits("ALTER TABLE metrics.x ADD COLUMN id integer GENERATED ALWAYS AS IDENTITY;"))
        assertEquals(1, hits("CREATE TABLE metrics.x (id integer NOT NULL, a TEXT, CONSTRAINT pk PRIMARY KEY (id));"))
        assertEquals(1, hits("ALTER TABLE metrics.item_stage ALTER COLUMN id TYPE integer;"))
        assertEquals(1, hits("ALTER TABLE metrics.item_stage ALTER COLUMN id SET DATA TYPE int4;"))
        assertEquals(1, hits("CREATE SEQUENCE metrics.x_seq AS integer;"))
        assertEquals(1, hits("ALTER SEQUENCE norm.x_seq AS smallint;"))
        assertEquals(1, hits("CREATE UNLOGGED TABLE metrics.x (id SERIAL PRIMARY KEY);"))
        assertEquals(1, hits("ALTER TABLE IF EXISTS metrics.x ADD COLUMN id SERIAL;"))
        assertEquals(1, hits("ALTER TABLE ONLY metrics.x ADD COLUMN id SERIAL;"))
        assertEquals(1, hits("CREATE TABLE \"metrics\".x (id SERIAL PRIMARY KEY);"))
        assertEquals(1, hits("CREATE TABLE \"norm\".\"x\" (id SERIAL PRIMARY KEY);"))
        assertEquals(1, hits("SET search_path TO metrics;"))
        assertEquals(1, hits("SET LOCAL search_path = metrics, public;"))
        // Spared: wide ids, composite and foreign keys, other schemas, comments, wide sequences and ALTERs.
        assertEquals(0, hits("CREATE TABLE metrics.x (id BIGSERIAL PRIMARY KEY);"))
        assertEquals(0, hits("CREATE TABLE metrics.x (id BIGINT PRIMARY KEY);"))
        assertEquals(0, hits("CREATE TABLE metrics.x (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY);"))
        assertEquals(
            0,
            hits("CREATE TABLE metrics.x (c INTEGER NOT NULL REFERENCES source_connections(id), a BIGINT, PRIMARY KEY (c, a));"),
        )
        assertEquals(0, hits("CREATE TABLE metrics.x (a INTEGER NOT NULL, v NUMERIC(8, 2) NOT NULL PRIMARY KEY);"))
        assertEquals(0, hits("CREATE TABLE metrics.team_capacity_defaults (team_id INTEGER PRIMARY KEY REFERENCES teams(id), m INT);"))
        assertEquals(0, hits("CREATE TABLE metrics.x (team_id INTEGER NOT NULL REFERENCES teams(id), PRIMARY KEY (team_id));"))
        assertEquals(0, hits("ALTER TABLE metrics.x ALTER COLUMN id TYPE bigint;"))
        assertEquals(0, hits("CREATE SEQUENCE metrics.x_seq AS bigint;"))
        assertEquals(0, hits("CREATE TABLE teams2 (id SERIAL PRIMARY KEY);"))
        assertEquals(0, hits("CREATE TABLE public.teams2 (id SERIAL PRIMARY KEY);"))
        assertEquals(0, hits("ALTER TABLE public.x ALTER COLUMN id TYPE integer;"))
        assertEquals(0, hits("-- CREATE TABLE metrics.x (id SERIAL PRIMARY KEY);"))
    }

    private fun migrations(): List<Pair<Int, Path>> =
        migrationDir.listDirectoryEntries("V*__*.sql")
            .map { (Regex("""V(\d+)__""").find(it.name) ?: error("unparseable migration name ${it.name}")).groupValues[1].toInt() to it }
            .sortedBy { it.first }

    /** One entry per offending statement (comments stripped): a 32-bit id in a `raw`/`norm`/`metrics` object, or a search_path. */
    private fun narrowIdFindings(sql: String): List<String> =
        sql.lineSequence().map { it.substringBefore("--") }.joinToString("\n").split(';')
            .map { it.trim().replace(Regex("""\s+"""), " ") }
            .filter { it.isNotEmpty() && (SEARCH_PATH.containsMatchIn(it) || isNarrowIdStatement(it)) }
            .map { it.take(STATEMENT_PREVIEW) }

    private fun isNarrowIdStatement(statement: String): Boolean {
        if (!OBJECT_IN_SCOPE.containsMatchIn(statement)) return false
        if (SEQUENCE_STATEMENT.containsMatchIn(statement)) return NARROW_SEQUENCE.containsMatchIn(statement)
        if (SERIAL.containsMatchIn(statement) || NARROWING_ALTER.containsMatchIn(statement)) return true
        val keyedAlone = TABLE_LEVEL_KEY.findAll(statement).map { it.groupValues[1].trim('"').lowercase() }.toSet()
        return NARROW_COLUMN.findAll(statement).any { column ->
            val tail = column.groupValues[2]
            val foreignKey = REFERENCES.containsMatchIn(tail)
            IDENTITY_OR_NEXTVAL.containsMatchIn(tail) ||
                (!foreignKey && (INLINE_KEY.containsMatchIn(tail) || column.groupValues[1].trim('"').lowercase() in keyedAlone))
        }
    }

    private companion object {
        const val LAST_GRANDFATHERED_VERSION = 33
        const val STATEMENT_PREVIEW = 120
        const val NARROW = "(?:integer|int|int4|smallint|int2)(?![A-Za-z0-9_])"
        val IC = RegexOption.IGNORE_CASE

        /** CREATE / ALTER TABLE or SEQUENCE on an object of one of the three row-churn schemas (quoted or not). */
        val OBJECT_IN_SCOPE = Regex(
            """^(?:CREATE|ALTER) (?:UNLOGGED )?(?:TABLE|SEQUENCE) (?:IF NOT EXISTS |IF EXISTS |ONLY )*"?(?:raw|norm|metrics)"?\.""",
            IC,
        )
        val SEQUENCE_STATEMENT = Regex("""^(?:CREATE|ALTER) SEQUENCE """, IC)
        val NARROW_SEQUENCE = Regex("""\bAS $NARROW""", IC)
        val SEARCH_PATH = Regex("""\bSET (?:LOCAL |SESSION )?search_path\b""", IC)

        /** `SERIAL`, `SERIAL4`, `SMALLSERIAL`, `SERIAL2` - not `BIGSERIAL` / `SERIAL8`. */
        val SERIAL = Regex("""(?<![A-Za-z0-9_])(?:small)?serial[24]?(?![A-Za-z0-9_])""", IC)

        /** `ALTER COLUMN <col> [SET DATA] TYPE integer|int|int4|smallint|int2` - would undo a widening. */
        val NARROWING_ALTER = Regex("""\bALTER COLUMN "?[a-z_][a-z0-9_]*"? (?:SET DATA )?TYPE $NARROW""", IC)

        /** A narrow integer column definition: group 1 the name, group 2 the rest of it (up to the next comma). */
        val NARROW_COLUMN = Regex("""[\s(,]("?[a-z_][a-z0-9_]*"?) $NARROW([^,]*)""", IC)
        val IDENTITY_OR_NEXTVAL = Regex("""\bGENERATED (?:ALWAYS|BY DEFAULT) AS IDENTITY\b|\bnextval\b""", IC)
        val INLINE_KEY = Regex("""\bPRIMARY KEY\b""", IC)
        val REFERENCES = Regex("""\bREFERENCES\b""", IC)

        /** A table-level `PRIMARY KEY (col)` over exactly one column (optionally `CONSTRAINT name`d). */
        val TABLE_LEVEL_KEY = Regex("""\bPRIMARY KEY \(("?[a-z_][a-z0-9_]*"?)\)""", IC)
    }
}
